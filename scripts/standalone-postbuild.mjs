#!/usr/bin/env node
/**
 * Post-build for `output: "standalone"` (Hostinger Node.js Web App). Run from the repo root after `next build`:
 *   node scripts/standalone-postbuild.mjs
 * - Next does not copy `.next/static` or `public` into the standalone server: copy them next to its server.js.
 * - With outputFileTracingRoot = monorepo root, Next puts the server at standalone/apps/web/server.js: add a tiny
 *   standalone/server.js wrapper at the root that binds 0.0.0.0 (hosts may set HOSTNAME to the machine name) and
 *   keeps PORT from the environment.
 * - Safety net: if the Prisma query engine was not traced, copy the generated client into the standalone node_modules.
 * Cross-platform, no dependencies.
 */
import { cpSync, existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const web = join(root, "apps/web");
const dist = join(web, process.env.NEXT_DIST || ".next");
const standalone = join(dist, "standalone");
const nestedServer = join(standalone, "apps/web/server.js");

function fail(msg) {
  console.error(`[standalone-postbuild] ${msg}`);
  process.exit(1);
}

if (!existsSync(standalone)) fail(`${standalone} not found: is output: "standalone" set in apps/web/next.config.mjs?`);
if (!existsSync(nestedServer)) fail(`${nestedServer} not found`);

// 1. Static chunks and public files, next to the nested server.js (it serves them relative to its own folder).
const staticSrc = join(dist, "static");
if (!existsSync(staticSrc)) fail(`${staticSrc} not found`);
cpSync(staticSrc, join(standalone, "apps/web", ".next/static"), { recursive: true });
const publicSrc = join(web, "public");
if (existsSync(publicSrc)) cpSync(publicSrc, join(standalone, "apps/web/public"), { recursive: true });

// 2. Root wrapper so `node apps/web/.next/standalone/server.js` (or a host looking for <output>/standalone/server.js) works.
writeFileSync(
  join(standalone, "server.js"),
  `// Generated by scripts/standalone-postbuild.mjs. Do not edit.
// Bind every interface: some hosts set HOSTNAME to the machine name, which Next would otherwise listen on.
process.env.HOSTNAME = process.env.BIND_HOST || "0.0.0.0";
process.env.PORT = process.env.PORT || "3000";
require("./apps/web/server.js");
`,
);

// 3. Prisma engine safety net.
const tracedPrisma = join(standalone, "node_modules/.prisma/client");
const hasEngine = (dir) => existsSync(dir) && readdirSync(dir).some((f) => /^libquery_engine-.*\.node$|^query-engine-/.test(f));
if (!hasEngine(tracedPrisma)) {
  const generated = join(root, "node_modules/.prisma/client");
  if (!hasEngine(generated)) fail(`Prisma query engine not found in ${generated}: did \`prisma generate\` run?`);
  cpSync(generated, tracedPrisma, { recursive: true });
  console.log("[standalone-postbuild] Prisma client/engine copied into the standalone node_modules");
}

const engines = readdirSync(tracedPrisma).filter((f) => f.startsWith("libquery_engine-") || f.startsWith("query-engine-"));
console.log(`[standalone-postbuild] OK → ${join(standalone, "server.js")} (Prisma engines: ${engines.join(", ")})`);
